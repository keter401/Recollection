using System.Collections;
using UnityEngine;

// テレポート時のディゾルブエフェクトを制御するクラス
// StartDissolve()でプレイヤーを消し、ReverseDissolve()で目標地点に出現させる
// 呼び出し側でInputPermissionを制御することで、テレポート中の誤操作を防ぐ
public class TeleportEffectController : MonoBehaviour
{
	// ======================================================================================================================================================
	// インスペクター設定 [◆]
	// ======================================================================================================================================================

	// ディゾルブシェーダーのマテリアル
	[SerializeField] private Material dissolveShaderMaterial;

	// ディゾルブアニメーションの再生時間（秒）
	[SerializeField] private float duration = 0.5f;

	// ======================================================================================================================================================
	// 内部状態 [◆]
	// ======================================================================================================================================================

	// マテリアルのインスタンス（他オブジェクトへの影響を防ぐために複製して使用）
	private Material instanceMaterial;

	// 元のマテリアル（ReverseDissolve完了後に復元する）
	private Material originalMaterial;

	// ディゾルブ対象のRenderer
	private Renderer targetRenderer;

	// 実行中のコルーチンの参照（重複実行を防ぐために使用）
	private Coroutine dissolveRoutine;

	// ======================================================================================================================================================
	// 初期化 [◆]
	// ======================================================================================================================================================
	// 起動時に元のマテリアルを保存し、ディゾルブ用マテリアルをインスタンス化する
	private void Awake()
	{
		targetRenderer = GetComponentInChildren<Renderer>();

		// 元のマテリアルを保存（ReverseDissolve完了後の復元に使用）
		originalMaterial = targetRenderer.sharedMaterial;

		// Dissolve用マテリアルを複製してインスタンス化
		// インスタンス化することで他のオブジェクトへの影響を防ぐ
		instanceMaterial = new Material(dissolveShaderMaterial);
	}

	// ======================================================================================================================================================
	// テレポート開始（消える） [◆]
	// ======================================================================================================================================================
	// ディゾルブエフェクトを再生してプレイヤーを消す
	// 呼び出し側でInputPermission.move = false を設定してから呼ぶこと
	public void StartDissolve()
	{
		ApplyMaterial(instanceMaterial);

		// 実行中のコルーチンを安全に停止してから再起動
		if (dissolveRoutine != null) StopCoroutine(dissolveRoutine);
		dissolveRoutine = StartCoroutine(Dissolve(0f, 1f, EaseIn));
	}

	// ======================================================================================================================================================
	// テレポート完了（現れる） [◆]
	// ======================================================================================================================================================
	// 逆方向のディゾルブエフェクトを再生してプレイヤーを出現させる
	// 完了後に元のマテリアルへ自動復元する
	// 呼び出し側でInputPermission.move = true を設定してから呼ぶこと
	public void ReverseDissolve()
	{
		ApplyMaterial(instanceMaterial);

		// 実行中のコルーチンを安全に停止してから再起動
		if (dissolveRoutine != null) StopCoroutine(dissolveRoutine);
		dissolveRoutine = StartCoroutine(DissolveAndRestore(1f, 0f, EaseOut));
	}

	// ======================================================================================================================================================
	// マテリアル切り替え [◆]
	// ======================================================================================================================================================
	// 現在適用されているマテリアルと異なる場合のみ切り替える
	private void ApplyMaterial(Material mat)
	{
		if (targetRenderer.material != mat)
		{
			targetRenderer.material = mat;
		}
	}

	// ======================================================================================================================================================
	// ディゾルブコルーチン [◆]
	// ======================================================================================================================================================
	// DissolveProgressを from → to へ補間しながらシェーダーに反映する
	// easeFunc でイージングを適用して滑らかな演出を実現する
	private IEnumerator Dissolve(float from, float to, System.Func<float, float> easeFunc)
	{
		float time = 0f;
		while (time < duration)
		{
			float t      = time / duration;
			float easedT = easeFunc(t);
			float value  = Mathf.Lerp(from, to, easedT);

			// シェーダーのDissolveProgressを更新
			instanceMaterial.SetFloat("DissolveProgress", value);

			time += Time.deltaTime;
			yield return null;
		}

		// 最終値を確実に設定
		instanceMaterial.SetFloat("DissolveProgress", to);
	}

	// ======================================================================================================================================================
	// ディゾルブ後にマテリアルを復元するコルーチン [◆]
	// ======================================================================================================================================================
	// Dissolveが完了したら元のマテリアルへ復元する
	// ReverseDissolve完了後に真っ白のまま残るバグを防ぐ
	private IEnumerator DissolveAndRestore(float from, float to, System.Func<float, float> easeFunc)
	{
		yield return Dissolve(from, to, easeFunc);

		// 元のマテリアルへ復元
		ApplyMaterial(originalMaterial);
	}

	// ======================================================================================================================================================
	// イージング関数 [◆]
	// ======================================================================================================================================================

	// Ease-In（始めはゆっくり、だんだん速く）
	private float EaseIn(float t)
	{
		return t * t * t;
	}

	// Ease-Out（始めは速く、だんだん遅く）
	private float EaseOut(float t)
	{
		return 1f - Mathf.Pow(1f - t, 3f);
	}
}
